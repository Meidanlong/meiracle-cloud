#!/usr/bin/env bash
# ============================================================================
# 停止并移除全部中间件容器（保留数据卷）。如需连同数据卷一起清理，见下方注释。
# ============================================================================
set -euo pipefail
cd "$(dirname "$0")/.."

echo "[INFO] 停止并移除中间件容器..."
docker compose down

# 如需彻底清理数据卷（不可恢复），取消下一行注释：
# docker compose down -v
echo "[DONE] 已停止。数据卷（mysql-data / redis-data / nacos-data 等）已保留。"
